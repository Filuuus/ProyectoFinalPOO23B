    private void EnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EnviarActionPerformed
        Archivo archivo = new Archivo();
        archivo.crearArchivo();
        
        if (nameTextField.getText().equals("") || apellidosTextField.getText().equals("") || carreraTextField.getText().equals("") || ((MasculinoButton.isSelected()== false) && (FemeninoButton.isSelected()==false))) {
            JOptionPane.showMessageDialog(null, "Por favor, llene los campos.");
        }else{
        
        String nombre = nameTextField.getText ();
        String apellidos = apellidosTextField.getText ();
        String carrera = carreraTextField.getText();
        String sexo = sexoSeleccion();
        
        Persona persona = new Persona (nombre, apellidos, carrera,sexo);
        archivo.escribirEnArchivo(persona);
        
        JOptionPane.showMessageDialog(null, "Registro guardado.");
        
        Reset();
        
        }
    }//GEN-LAST:event_EnviarActionPerformed

