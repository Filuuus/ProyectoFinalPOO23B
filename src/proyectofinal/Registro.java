    private String sexoSeleccion(){
        String sexo = "";
        if(MasculinoButton.isSelected() == true){
            sexo = "Masculino";
        }else if(FemeninoButton.isSelected() == true){
            sexo = "Femenino";
        }
        return sexo;
    }
    
    private void Reset(){
        nameTextField.setText("");
        apellidosTextField.setText("");
        carreraTextField.setText("");
        MasculinoButton.setSelected(false);
        FemeninoButton.setSelected(false);
    }
